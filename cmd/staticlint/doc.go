// Package main предоставляет multichecker для статического анализа Go-кода.
//
// Multichecker включает следующие группы анализаторов:
//
//  1. Стандартные анализаторы из golang.org/x/tools/go/analysis/passes
//     Включают проверки корректности кода, использования стандартной библиотеки,
//     безопасности и производительности.
//
//  2. Анализаторы SA из staticcheck.io
//     SA-анализаторы выполняют глубокий статический анализ кода, выявляя
//     потенциальные ошибки, неправильное использование API, проблемы
//     производительности и стиля.
//
//  3. Анализаторы ST из staticcheck.io (stylecheck)
//     ST-анализаторы проверяют соответствие кода рекомендациям по стилю Go.
//
//  4. Собственный анализатор exitcheck
//     Запрещает использование аварийного завершения программы вне функции main.main:
//     - os.Exit (разрешен только в main.main)
//     - panic (запрещен везде)
//     - log.Fatal, log.Panic (запрещены везде)
//     - logger.Fatal (zap) (запрещен везде)
//
// Использование:
//
//	# Сборка
//	go build -o staticlint ./cmd/staticlint/
//
//	# Запуск
//	./staticlint ./...
//
//	# Запуск с go vet
//	go vet -vettool=./staticlint ./...
//
//	# Фильтрация по имени анализатора
//	./staticlint -include=SA ./...
//	./staticlint -include=exitcheck ./...
//
//	# Проверка конкретного пакета
//	./staticlint ./internal/handlers/...
